export function filterDestinations(query = '') {
  const normalized = String(query ?? '').trim().toLowerCase();

  if (!normalized) {
    return DESTINATIONS;
  }

  return DESTINATIONS.filter((place) =>
    [
      place.name,
      place.city,
      place.country,
      place.category,
      place.description,
    ].some((value) =>
      String(value ?? '').toLowerCase().includes(normalized),
    ),
  );
}

export function getDestinationByName(name) {
  const normalized = String(name ?? '').trim().toLowerCase();

  return (
    DESTINATIONS.find(
      (place) => place.name.toLowerCase() === normalized,
    ) ?? null
  );
}
